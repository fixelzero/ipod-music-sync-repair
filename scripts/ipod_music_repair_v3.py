#!/usr/bin/env python3
"""Safely inspect and optionally request cloud downloads for iPod sync failures.
Python 3.9+, macOS Music. Never deletes library entries or local files.
"""
import argparse
import csv
import os
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path

INSPECT = r'''
on run argv
    set wantedID to item 1 of argv
    tell application "Music"
        set foundTracks to (every track of library playlist 1 whose persistent ID is wantedID)
        if (count of foundTracks) is not 1 then return "LOOKUP_ERROR" & tab & "Expected one persistent ID match; got " & (count of foundTracks)
        set t to item 1 of foundTracks
        set cloudText to "unknown"
        try
            set cloudText to (cloud status of t) as text
        end try
        set locationText to ""
        set locationState to "NO_LOCATION"
        try
            set f to location of t
            if f is not missing value then
                set locationText to POSIX path of f
                set locationState to "PATH_REPORTED"
            end if
        on error errText
            set locationState to "LOCATION_ERROR"
        end try
        return locationState & tab & cloudText & tab & locationText
    end tell
end run
'''

DOWNLOAD = r'''
on run argv
    set wantedID to item 1 of argv
    tell application "Music"
        set foundTracks to (every track of library playlist 1 whose persistent ID is wantedID)
        if (count of foundTracks) is not 1 then error "Persistent ID did not uniquely identify a track"
        set t to item 1 of foundTracks
        download t
        return "DOWNLOAD_REQUESTED"
    end tell
end run
'''

def apple(script, ident, timeout):
    try:
        p = subprocess.run(['osascript', '-e', script, ident], capture_output=True, text=True, timeout=timeout)
        if p.returncode:
            return False, (p.stderr or p.stdout).strip()
        return True, p.stdout.strip()
    except subprocess.TimeoutExpired:
        return False, 'Timed out waiting for Music'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('matches', type=Path, help='ipod_music_matches.csv from Version 2')
    ap.add_argument('--download', action='store_true', help='Request downloads for unambiguous eligible tracks only')
    ap.add_argument('--timeout', type=int, default=40)
    ap.add_argument('--output', type=Path, default=Path.home() / 'Desktop' / 'ipod_repair_v3_report.csv')
    args = ap.parse_args()
    if not args.matches.is_file():
        ap.error('CSV not found: ' + str(args.matches))
    with args.matches.open(encoding='utf-8-sig', newline='') as f:
        rows = list(csv.DictReader(f))
    required = {'Title', 'Status', 'Artist', 'Album', 'Persistent ID', 'Cloud status'}
    if not rows or not required.issubset(rows[0]):
        ap.error('CSV must be the matching report generated by Version 2')
    matches = [r for r in rows if r['Status'] == 'MATCH' and r['Persistent ID'].strip()]
    groups = defaultdict(list)
    for r in matches:
        groups[r['Title']].append(r)
    print(f'Loaded {len(matches)} matching tracks across {len(groups)} titles.', flush=True)
    print('Inspecting local file paths. No deletions will occur.', flush=True)
    checked = []
    cache = {}
    for i, r in enumerate(matches, 1):
        pid = r['Persistent ID'].strip()
        print(f'[{i}/{len(matches)}] {r["Artist"]} — {r["Title"]}', flush=True)
        if pid in cache:
            ok, output = cache[pid]
        else:
            ok, output = apple(INSPECT, pid, args.timeout)
            cache[pid] = (ok, output)
        if not ok:
            state, cloud, path, detail = 'INSPECTION_ERROR', '', '', output
        else:
            parts = output.split('\t', 2)
            if len(parts) < 3 or parts[0] == 'LOOKUP_ERROR':
                state, cloud, path, detail = 'INSPECTION_ERROR', '', '', output
            else:
                loc_state, cloud, path = parts
                if loc_state == 'PATH_REPORTED' and path:
                    state = 'FILE_EXISTS' if os.path.isfile(path) else 'FILE_MISSING'
                elif loc_state == 'NO_LOCATION':
                    state = 'NO_LOCAL_PATH'
                else:
                    state = 'UNKNOWN_LOCATION'
                detail = ''
        checked.append(dict(r, **{'Local status': state, 'Current cloud status': cloud,
                                  'Local path': path, 'Action': 'NONE', 'Action details': detail}))
    # Only act when a title has precisely one *verified missing* candidate.
    # A title with no path can be cloud-only, but could also be a different recording.
    by_title = defaultdict(list)
    for r in checked:
        by_title[r['Title']].append(r)
    for title, group in by_title.items():
        missing = [r for r in group if r['Local status'] == 'FILE_MISSING']
        if len(missing) != 1:
            for r in group:
                r['Action'] = 'REVIEW_AMBIGUOUS' if len(missing) > 1 else 'NO_VERIFIED_MISSING_FILE'
            continue
        candidate = missing[0]
        cloud = candidate['Current cloud status'].lower().strip()
        if cloud not in ('matched', 'uploaded'):
            candidate['Action'] = 'REVIEW_CLOUD_STATUS'
            continue
        candidate['Action'] = 'ELIGIBLE_FOR_DOWNLOAD'
        if args.download:
            ok, output = apple(DOWNLOAD, candidate['Persistent ID'].strip(), args.timeout)
            candidate['Action'] = 'DOWNLOAD_REQUESTED' if ok else 'DOWNLOAD_FAILED'
            candidate['Action details'] = output
            print('   ' + candidate['Action'] + (': ' + output[:160] if not ok else ''), flush=True)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    fields = ['Title','Status','Artist','Album','Persistent ID','Cloud status','Local status',
              'Current cloud status','Local path','Action','Action details']
    with args.output.open('w', encoding='utf-8-sig', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fields, extrasaction='ignore')
        writer.writeheader()
        writer.writerows(checked)
    print('\nLocal status:', dict(Counter(r['Local status'] for r in checked)), flush=True)
    print('Actions:', dict(Counter(r['Action'] for r in checked)), flush=True)
    print('Report:', args.output, flush=True)
    if args.download:
        print('Download requests are not proof of completed downloads. Re-run preview and sync only after checking files.', flush=True)
    else:
        print('Preview only. Inspect the report before using --download.', flush=True)

if __name__ == '__main__':
    main()
